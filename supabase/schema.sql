create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 120),
  phone text not null check (char_length(phone) <= 40),
  email text,
  enquiry_type text not null,
  property_type text,
  location text,
  electricity_bill numeric check (electricity_bill is null or electricity_bill >= 0),
  monthly_consumption numeric check (monthly_consumption is null or monthly_consumption >= 0),
  requested_system_size numeric check (requested_system_size is null or requested_system_size >= 0),
  calculator_inputs jsonb,
  calculator_results jsonb,
  message text check (message is null or char_length(message) <= 5000),
  consent_status boolean not null default false,
  enquiry_status text not null default 'New' check (enquiry_status in ('New','Contacted','Site Visit Requested','Site Visit Scheduled','Quotation Sent','Follow-up Required','Won','Lost')),
  internal_notes text,
  created_at timestamptz not null default now()
);
create index if not exists enquiries_created_at_idx on public.enquiries(created_at desc);
create index if not exists enquiries_status_idx on public.enquiries(enquiry_status);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  category text not null,
  brand text,
  model_number text,
  description text,
  specifications jsonb not null default '{}'::jsonb,
  price numeric,
  price_type text not null default 'Request a Quote' check (price_type in ('Fixed','Indicative','Range','Request a Quote','Unavailable')),
  availability text not null default 'Contact to Confirm Availability',
  warranty_details text,
  datasheet_url text,
  image_url text,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  reviewer_name text,
  review_source text not null,
  rating integer check (rating between 1 and 5),
  review_text text not null,
  review_date date,
  publication_permission boolean not null default false,
  verified boolean not null default false,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  location text,
  project_type text,
  capacity_kw numeric,
  project_description text,
  verified_metrics jsonb not null default '{}'::jsonb,
  images jsonb not null default '[]'::jsonb,
  completion_date date,
  publication_permission boolean not null default false,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.enquiries enable row level security;
alter table public.products enable row level security;
alter table public.reviews enable row level security;
alter table public.projects enable row level security;
